// Math/control execution in a mock canvas. This is not browser layout testing.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'docs/visualizations/finite_neck.html'), 'utf8');
const js = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const canvas = new Proxy({}, {get: () => () => {}, set: () => true});
const elements = Object.fromEntries([...html.matchAll(/id="([^"]+)"/g)].map(m => [m[1], {value: '', textContent: '', getContext: () => canvas}]));
elements.waist.value = '.16'; elements.amp.value = '.18';
const context = vm.createContext({document: {getElementById: id => elements[id]}, matchMedia: () => ({matches: true}), requestAnimationFrame: () => {}});
vm.runInContext(js, context);
const run = s => vm.runInContext(s, context);
const recorded = JSON.parse(fs.readFileSync(path.join(root, 'docs/images/finite_neck/contact.json'), 'utf8'));
assert.ok(Math.abs(run('tc') - recorded.contact_time) < 1e-10);
assert.equal(elements.play.textContent, 'Play');
elements.off.onclick(); assert.equal(run('tc'), null); assert.equal(elements.contact.disabled, true);
elements.weak.onclick(); assert.equal(run('tc'), null);
elements.example.onclick(); assert.ok(run('tc') > 0); assert.equal(elements.contact.disabled, false);
elements.contact.onclick(); assert.equal(run('t'), run('tc')); assert.equal(run('playing'), false);
run('t=tc+.7;draw()');
assert.ok(run('branches(t)[0].at(-1).x < branches(t)[1].at(-1).x'));
assert.ok(run('branches(t).every(p=>p.at(-1).r===0 && p[0].r===1)'));
elements.time.oninput({target: {value: '2'}}); assert.equal(run('t'), 2);
elements.waist.value = '.30'; elements.waist.oninput(); assert.equal(run('tc'), null); assert.equal(run('t'), 0);
elements.example.onclick(); elements.play.onclick(); assert.equal(run('playing'), true);
elements.restart.onclick(); assert.equal(run('t'), 0);
console.log('HTML math agrees with Python; wave controls, contact, caps, playback and scrubbing passed.');
