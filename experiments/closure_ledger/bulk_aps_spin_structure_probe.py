"""Probe C -- bulk extension, APS inflow, and the Pin- mouth (PR #230).

> Framing: QFT on the *fixed classical* throat geometry (geometry -> fields),
> not quantum gravity.

THE QUESTION
------------
Probe B leaves the two RP^3 spin structures distinguished ONLY by the
determinant phase, through eta = +/-1/4 -- identical moduli, identical
vacuum energy, h = 0 for both.  A phase is not an energy, so it cannot make
one sector cheaper.  What a phase CAN do is fail to extend: anomaly inflow
and the APS index theorem constrain which boundary spin structures bound a
bulk.  If only one extended, that would select the sector outright.  This
probe checks.

THE OBJECTS
-----------
  Y^3 = RP^3 = L(2,1), the exterior 3-manifold, with either spin structure.
  X^4 = the disk bundle over S^2 of Euler number e = +/-2.  Its boundary is
        the lens space L(2,1) = RP^3, and it is spin precisely because e is
        EVEN (the disk bundle over S^2 with Euler number e is spin iff e is
        even) -- so it is an admissible bulk, explicitly.

THE ANSWER: BOTH EXTEND -- INFLOW DOES NOT SELECT
--------------------------------------------------
Omega_3^{Spin} = 0.  Every spin 3-manifold bounds a spin 4-manifold, so
BOTH spin structures on RP^3 extend, and the APS index

    ind(D_X) = integral_X A-hat  -  (h + eta)/2 ,   h = 0 ,  eta = +/-1/4

is an integer in each case, with the fractional boundary term -/+1/8
cancelled by the bulk A-hat integral.  There is no obstruction on either
side.

*** So anomaly inflow does NOT select the twist sector.  Both remain
admissible, which is exactly the precondition that triggers Probe D. ***

WHERE A REAL SELECTION RULE *DOES* APPEAR: THE Pin- MOUTH
----------------------------------------------------------
The mouth is RP^2, which is non-orientable and carries Pin- (#169/#170).
The relevant bordism group is Omega_2^{Pin-} = Z_8, generated by RP^2, and
the invariant is the Arf-Brown-Kervaire class, ABK(RP^2) = +/-1 mod 8 for
its two Pin- structures.  A throat has TWO mouths, and their classes ADD:

    opposite Pin- structures :  (+1) + (-1) = 0 mod 8   ->  BOUNDS
    same Pin- structures     :  (+1) + (+1) = 2 mod 8   ->  DOES NOT BOUND

so the two mouths of one throat MUST carry OPPOSITE Pin- structures.

That is a genuine, derived selection rule -- and the repo already asserts
it as a modelling convention: ``ThroatDefect``/``ConjugatePair`` enforce
``mouth_a.orientation == -mouth_b.orientation`` by assertion.  Here it is
forced by Z_8 bordism rather than assumed.  Note carefully what it does and
does not do: it constrains the two mouths RELATIVE to each other; it says
nothing about which absolute sector a network occupies, so it does not
answer the selection question either.

Tests:
  T1. The objects: Y^3, X^4, and why X^4 is spin.
  T2. APS index per boundary spin structure.
  T3. Do both lifts extend?  (Omega_3^{Spin} = 0.)
  T4. The Pin-/ABK class of the RP^2 mouth, and how paired mouths combine.
  T5. Assessment, and the Probe D precondition.

Verdict:
  BOTH_SPIN_STRUCTURES_EXTEND_SO_INFLOW_DOES_NOT_SELECT_BUT_ABK_FORCES_THE
  _TWO_MOUTHS_OF_A_THROAT_TO_CARRY_OPPOSITE_PIN_MINUS_STRUCTURES
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

import numpy as np

# Standard bordism input (cited, not derived here).
OMEGA_SPIN = {0: 'Z', 1: 'Z2', 2: 'Z2', 3: '0', 4: 'Z'}
OMEGA_2_PIN_MINUS = 'Z8'
ABK_RP2 = (+1, -1)          # the two Pin- structures on RP^2, mod 8


def aps_index_boundary_term(eta: float, h: int = 0) -> float:
    """The APS boundary defect: ind(D_X) = int_X A-hat - (h + eta)/2."""
    return -(h + eta) / 2.0


