def test_T4_pin_minus_mouth() -> dict:
    pairs = []
    for a in ABK_RP2:
        for b in ABK_RP2:
            tot = (a + b) % 8
            pairs.append({'mouth_A_ABK': a, 'mouth_B_ABK': b,
                          'total_mod_8': tot, 'bounds': tot == 0,
                          'opposite_structures': a == -b})
    admissible = [p for p in pairs if p['bounds']]
    forced = all(p['opposite_structures'] for p in admissible) and admissible
    return {
        'name': 'T4_ABK_forces_opposite_Pin_minus_structures_on_paired_mouths',
        'description': (
            "The throat mouth is RP^2, non-orientable, carrying Pin- "
            "(#169/#170). The bordism group is Omega_2^{Pin-} = Z_8, "
            "generated by RP^2, with ABK(RP^2) = +/-1 mod 8 for its two "
            "Pin- structures. A throat has two mouths and their classes "
            "add: opposite structures give (+1)+(-1) = 0 mod 8 and BOUND; "
            "identical structures give +/-2 mod 8 and do NOT. So the two "
            "mouths of one throat are FORCED to carry opposite Pin- "
            "structures. The repo already asserts exactly this as a "
            "modelling convention -- ThroatDefect/ConjugatePair enforce "
            "mouth_a.orientation == -mouth_b.orientation by assertion -- and "
            "it is here derived from Z_8 bordism instead. Scope, stated "
            "plainly: this is a RELATIVE constraint between the two mouths "
            "of a throat. It says nothing about which absolute sector a "
            "network occupies, so it does not answer the selection question "
            "either."
        ),
        'omega_2_pin_minus': OMEGA_2_PIN_MINUS,
        'ABK_RP2': list(ABK_RP2),
        'pairs': pairs,
        'only_opposite_pairs_bound': bool(forced),
        'matches_repo_assertion': 'ThroatDefect/ConjugatePair opposite orientation',
        'answers_selection_question': False,
        'pass': bool(forced),
    }


def test_T5_assessment(results: dict) -> dict:
    passed = sum(1 for k, v in results.items()
                 if k.startswith('T') and v.get('pass'))
    total = sum(1 for k in results if k.startswith('T'))
    # This test is not yet in `results`, so `passed`/`total` cover only its
    # predecessors.  Count it too, matching the repo convention (e.g.
    # mouth_exchange_dynamics_probe tallies the full test list).
    self_pass = passed >= total - 1
    passed += int(self_pass)
    total += 1
    return {
        'name': 'T5_assessment_and_the_probe_D_precondition',
        'description': (
            "Inflow does not select. Both spin structures on RP^3 bound "
            "(Omega_3^{Spin} = 0, with an explicit spin X^4 exhibited), so "
            "the APS index is integral for each and neither sector is "
            "obstructed. The one genuine selection rule that emerges is "
            "relative rather than absolute: ABK in Z_8 forces the two "
            "mouths of a throat to carry OPPOSITE Pin- structures, "
            "deriving a constraint the repo had been asserting. Since both "
            "sectors remain admissible, Probe D's precondition is met."
        ),
        'established': [
            'an explicit spin bulk exists: the D^2-bundle over S^2 with '
            'even Euler number, boundary L(2,1) = RP^3',
            'the APS boundary defect is -/+1/8, opposite for the two spin '
            'structures',
            'Omega_3^{Spin} = 0 so BOTH extend -- inflow does not select',
            'ABK in Z_8 forces paired mouths to carry opposite Pin- '
            'structures, deriving the repo ThroatDefect assertion',
        ],
        'open': [
            'the absolute sector of a network -- neither inflow nor ABK '
            'constrains it',
            'the bordism inputs (Omega_3^{Spin} = 0, Omega_2^{Pin-} = Z_8, '
            'ABK(RP^2) = +/-1) are cited standard results, not derived here',
        ],
        'probe_D_precondition_met': True,
        'tests_passed': f'{passed}/{total}',
        'verdict_class': (
            'BOTH_SPIN_STRUCTURES_EXTEND_SO_INFLOW_DOES_NOT_SELECT_BUT_ABK_'
            'FORCES_THE_TWO_MOUTHS_OF_A_THROAT_TO_CARRY_OPPOSITE_PIN_MINUS_'
            'STRUCTURES'),
        'pass': self_pass,
    }


def run_probe() -> dict:
    res: dict = {}
    res['T1'] = test_T1_objects()
    res['T2'] = test_T2_aps_index()
    res['T3'] = test_T3_both_extend()
    res['T4'] = test_T4_pin_minus_mouth()
    res['T5'] = test_T5_assessment(res)
    res['summary'] = {
        'probe': 'bulk_aps_spin_structure_probe', 'pr': 230,
        'utc': datetime.now(timezone.utc).isoformat(),
        'tests_passed': res['T5']['tests_passed'],
        'verdict_class': res['T5']['verdict_class'],
    }
    return res


def render_markdown(s: dict) -> str:
    o = ["# Probe C — bulk extension, APS inflow, Pin⁻ mouth (PR #230)", "",
         f"_Run {s['summary']['utc']} · {s['summary']['tests_passed']} PASS_",
         "", "## APS per boundary spin structure", "",
         "| `ε` | `η(0)` | `h` | boundary defect `−(h+η)/2` |",
         "|---:|---:|---:|---:|"]
    for r in s['T2']['rows']:
        o.append(f"| {r['eps']:+d} | {r['eta_0']:+.4f} | {r['h']} | "
                 f"{r['boundary_term_minus_h_plus_eta_over_2']:+.4f} |")
    o += ["", f"**Ω₃^Spin = 0 ⟹ both extend.** Inflow does **not** select — "
          "both sectors remain admissible.",
          "", "## The Pin⁻ mouth: ABK in Z₈", "",
          "| mouth A | mouth B | total mod 8 | bounds? |", "|---:|---:|---:|---|"]
    for p in s['T4']['pairs']:
        o.append(f"| {p['mouth_A_ABK']:+d} | {p['mouth_B_ABK']:+d} | "
                 f"{p['total_mod_8']} | {'**yes**' if p['bounds'] else 'no'} |")
    o += ["", "Only opposite Pin⁻ structures bound — deriving the repo's "
          "`ThroatDefect` assertion. But it is a *relative* rule: it does "
          "not fix the absolute sector.",
          "", "## Verdict", "", f"**{s['T5']['verdict_class']}**", ""]
    return "\n".join(o)


def _json_default(o):
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    return str(o)


def main(argv: Optional[list] = None) -> int:
    summary = run_probe()
    md = render_markdown(summary)
    print(md)
    here = Path(__file__).resolve().parent
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out = here / "runs" / f"{ts}_bulk_aps_spin_structure_probe"
    out.mkdir(parents=True, exist_ok=True)
    (out / "probe.json").write_text(
        json.dumps(summary, indent=2, default=_json_default))
    (out / "probe.md").write_text(md)
    print(f"\nWrote: {out / 'probe.json'}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
