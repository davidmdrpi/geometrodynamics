    sg = np.arange(-L, L + dx / 2, dx)
    V = mx.v_bridge_half(np.abs(sg), 0.3)
    Nn = len(sg)
    lap = (np.diag(-2.0 * np.ones(Nn)) + np.diag(np.ones(Nn - 1), 1)
           + np.diag(np.ones(Nn - 1), -1)) / dx ** 2
