def test_T3_ellipse_mixer() -> dict:
    if 'T3' in _CACHE:
        return _CACHE['T3']
    cf = 2.0 * (1.0 - math.cos(2 * PI / _N))       # = 2 - sqrt2 at N = 8
    rows, devs, phs = [], [], []
    for phi0 in (0.0, 0.7, 1.9):
        for eps in (1e-3, 2e-3):
            me = complex(np.vdot(kvec(1), fiber_H(eps, phi0) @ kvec(-1)))
            devs.append(abs(abs(me) / (cf * eps) - 1.0))
            dph = (np.angle(me) - phi0 + PI) % (2 * PI) - PI
            phs.append(abs(dph))
            rows.append({'eps': eps, 'phi0': phi0,
                         'offdiag': abs(me), 'arg': float(np.angle(me))})
    cf_dev = float(max(devs))
    ph_dev = float(max(phs))
    # the exact m-pole selection rule: an m-deformation mixes only
    # Delta k = m at O(eps)
