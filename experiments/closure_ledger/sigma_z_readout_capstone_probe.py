# ── the elliptic fiber ──────────────────────────────────────────────────

def fiber_H(eps, phi0, m=2):
    """The discrete fiber circle (N_chi sites) with the metric
    perturbation R(chi) = 1 + eps cos(2 pi m chi/N + phi0): hopping
    t = 1/R_mid^2 on each link."""
    H = np.zeros((_N, _N), dtype=complex)
    for c in range(_N):
        mid = c + 0.5
        R = 1.0 + eps * math.cos(2 * PI * m * mid / _N + phi0)
        t = 1.0 / R ** 2
        H[c, (c + 1) % _N] -= t
        H[(c + 1) % _N, c] -= t
    for c in range(_N):
        H[c, c] = -(H[c, (c + 1) % _N] + H[c, (c - 1) % _N]).real
    return H


def kvec(k):
    c = np.arange(_N)
    return np.exp(2j * PI * k * c / _N) / math.sqrt(_N)


def qubit_restriction(phi):
    """The 2x2 qubit block of the m = 2 mouth harmonic at
    orientation phi (the L machinery, imported)."""
    diag = ml.chi_harmonic(2, cs._XA, phi)
    M = np.zeros((_N, _N), dtype=complex)
    for a, ka in enumerate(_KS):
        for b, kb in enumerate(_KS):
            M[a, b] = np.vdot(cs.mode(cs._XA, ka), diag * cs.mode(cs._XA, kb))
    return np.array([[M[_I1, _I1], M[_I1, _IM1]],
                     [M[_IM1, _I1], M[_IM1, _IM1]]])


